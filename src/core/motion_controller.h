#pragma once


/**
 * @file motion_controller.h
 * @brief Cascaded position/velocity torque-command synthesizer ("epsilon
 *        spring + damper") with a dynamic-bandwidth kinematic observer.
 *
 * MotorVectorSynthesis converts a measured position and a motion target into
 * a q-axis current command for the FOC current loop. It combines:
 *
 * 1. A third-order "ABY" position/velocity/acceleration observer driven by
 *    the measured position, whose bandwidth (cutoff frequency) adapts to the
 *    commanded velocity and is slew-rate limited for smoothness.
 * 2. An "epsilon spring": a saturating, S-curve-shaped position error term
 *    that produces full current only beyond @c epsilon_rev of error.
 * 3. A velocity damper built from a fast-tanh approximation of the estimated
 *    velocity error.
 * 4. Cascade anti-windup: when the downstream voltage loop reports saturation,
 *    the output current may only decrease relative to the last applied value,
 *    preventing integral/torque windup against a saturated plant.
 * 5. A thermal ring limit: the squared envelope i_lim_sq = P_nom / R
 *    (published by PtControl) caps the command magnitude, preserving its
 *    direction, so a hot or overdrive-spent motor is squeezed smoothly.
 *
 * Position units are revolutions encoded as int32 Q16.16
 * (65536 counts = 1 revolution); currents are in milliamperes.
 * Copyright 2026, creapunk
 * Licensed under the Apache License, Version 2.0
 */

#include <stdint.h>
#include <cmath>
#include "common.h"


struct MotorVectorSynthesis {
    // ── Epsilon-spring parameters ─────────────────────────────────
    float epsilon_rev = 0.0075f;   // Spring saturation width [rev]; was 0.0075. Bench 2026-09-15: 0.001 vibrates under load, 0.002 is the limit with the stock damper


    // ── Variable-bandwidth ABY observer parameters ────────────────
    float dt = 0.00005f;
    float obs_fc_min_hz = 25.0f;
    float obs_fc_max_hz = 100.0f;
    float obs_fc_per_rev_s = 150.0f;
    float obs_fc_slew_hz_s = 2000.0f;
    float b0_ff_rev_s2_per_ma = 0.0f;
    float obs_acc_limit_rev_s2 = 200000.0f;


    // ── Damping parameters ────────────────────────────────────────
    float damping_gain = 0.25f;
    float v_soft_rev_s = 0.25f;


    /**
     * Squared circular current (thermal) limit [A^2], published by PtControl
     * as P_nom / R. The ring check itself compares squared magnitudes, so
     * the caller supplies the limit ready-squared and this side stays free
     * of divisions on the hot path; the square root appears only when the
     * command actually sits outside the circle. A value <= 0 (unconfigured
     * limiter or unknown resistance) disables the ring limit entirely. The
     * command the loop works with is in amperes (DriveOutput::max_current_a
     * crosses into max_c), so no unit conversion is involved.
     */
    float i_lim_sq = INFINITY;



private:
    static inline float clampf(float x, float lo, float hi) {
        return (x < lo) ? lo : ((x > hi) ? hi : x);
    }

    // CLEANUP (P5.1): private signf() removed — reuse the shared one from common.h.

    // ── ABY observer state ────────────────────────────────────────
    float obs_pos_rev = 0.0f;
    float obs_vel_rev_s = 0.0f;
    float obs_acc_rev_s2 = 0.0f;
    float obs_fc_hz = 25.0f;


    /// Last Iq command generated by the 4 kHz outer controller.
    float last_applied_iq_ma = 0.0f;

    bool is_first_tick = true;


public:
    MotorVectorSynthesis() {}


    float getEstimatedPositionRev() const {
        return obs_pos_rev;
    }

    float getEstimatedVelocityRevS() const {
        return obs_vel_rev_s;
    }

    float getEstimatedAccelerationRevS2() const {
        return obs_acc_rev_s2;
    }

    float getObserverFcHz() const {
        return obs_fc_hz;
    }


    /**
     * Observer runs at every call, nominally 20 kHz.
     * Spring/damper regulation runs once per five calls, nominally 4 kHz.
     *
     * Between regulation ticks the previous Iq command is returned unchanged.
     */
    float tick(int32_t current_pos,
               int32_t target_pos,
               float target_vel,
               float max_c,
               bool is_volt_saturated) {
        const float inv_q16 = 1.0f / 65536.0f;
        const float meas_pos_rev = (float)current_pos * inv_q16;


        // ====================================================================
        // 0. Initialization
        // ====================================================================
        if (is_first_tick) {
            obs_pos_rev = meas_pos_rev;
            obs_vel_rev_s = 0.0f;
            obs_acc_rev_s2 = 0.0f;
            obs_fc_hz = obs_fc_min_hz;
            last_applied_iq_ma = 0.0f;
            is_first_tick = false;
        }


        // ====================================================================
        // 1. Dynamic ABY observer: runs every tick, at 20 kHz
        // ====================================================================
        float fc_target_hz =
            obs_fc_min_hz + obs_fc_per_rev_s * fabsf(target_vel);

        fc_target_hz = clampf(
            fc_target_hz,
            obs_fc_min_hz,
            obs_fc_max_hz
        );

        float max_df = obs_fc_slew_hz_s * dt;
        float df = clampf(
            fc_target_hz - obs_fc_hz,
            -max_df,
            max_df
        );

        obs_fc_hz += df;

        const float w = 2.0f * (float)M_PI * obs_fc_hz;
        const float l1 = 3.0f * w;
        const float l2 = 3.0f * w * w;
        const float l3 = w * w * w;

        const float acc_ff =
            b0_ff_rev_s2_per_ma * last_applied_iq_ma;

        const float err = meas_pos_rev - obs_pos_rev;

        obs_pos_rev += dt * (obs_vel_rev_s + l1 * err);

        obs_vel_rev_s += dt * (
            obs_acc_rev_s2 +
            acc_ff +
            l2 * err
        );

        obs_acc_rev_s2 += dt * (l3 * err);

        obs_acc_rev_s2 = clampf(
            obs_acc_rev_s2,
            -obs_acc_limit_rev_s2,
            obs_acc_limit_rev_s2
        );


        // ====================================================================
        // 2. Outer spring + damper: runs every fifth observer tick, at 4 kHz
        // ====================================================================

        // Position error in revolutions.
        float ep = (float)(target_pos - current_pos) * inv_q16;
        // float ep = (float)(target_pos) * inv_q16 - obs_pos_rev;


        // Smooth saturating epsilon spring.
        float t_linear = clampf(
            ep / (epsilon_rev + 1e-9f),
            -1.0f,
            1.0f
        );

        float sin_pow2_fast =
            t_linear *
            fabsf(t_linear) *
            (3.0f - 2.0f * t_linear);

        float Iq_spring = max_c * sin_pow2_fast;


        // Velocity damper.
        float vel_err = obs_vel_rev_s - target_vel;

        float norm_vel = vel_err / (v_soft_rev_s + 0.05f);

        float fast_tanh =
            norm_vel / (1.0f + fabsf(norm_vel));

        float Iq_damp =
            -max_c *
            damping_gain *
            fast_tanh *
            fast_tanh *
            signf(fast_tanh);


        // Requested q-axis current.
        float Iq_unlimited = Iq_spring + Iq_damp;
        float Iq = Iq_unlimited;


        // ====================================================================
        // 3. Cascade anti-windup: evaluated at the 4 kHz regulation rate
        // ====================================================================
        if (is_volt_saturated) {
            if ((Iq_unlimited > 0.0f &&
                 Iq_unlimited > last_applied_iq_ma) ||
                (Iq_unlimited < 0.0f &&
                 Iq_unlimited < last_applied_iq_ma)) {
                Iq = last_applied_iq_ma;
            }
        }


        Iq = clampf(Iq, -max_c, max_c);

        // ====================================================================
        // 4. Thermal ring limit: runs at the regulation rate
        // ====================================================================
        // The thermal envelope crosses SQUARED (i_lim_sq = P_nom / R,
        // published by PtControl) because the ring comparison itself needs
        // only squared magnitudes; the square root is taken only when the
        // command actually lies outside the circle. The loop output is the
        // torque current alone (the downstream FOC keeps id at zero), so its
        // square IS the squared magnitude of the current vector: the signed
        // pull-back below is exactly the radial projection onto the ring,
        // which clamps the envelope tighter than max_c when the motor runs
        // hot or overdrive is spent. i_lim_sq <= 0 keeps the clamp disabled.
        if (i_lim_sq > 0.0f) {
            const float i_sq = Iq * Iq;                       // Squared command magnitude [A^2]
            if (i_sq > i_lim_sq) {
                Iq = sqrtf(i_lim_sq) * signf(Iq);             // Pull back onto the ring, sign preserved
            }
        }

        last_applied_iq_ma = Iq;

        return Iq;
    }
};